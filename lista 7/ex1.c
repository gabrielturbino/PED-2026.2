//A) O que são pilhas e filas?
//Pilha: é uma estrutura de dados em que o último elemento a entrar é o primeiro a sair. 
//Essa regra é chamada de LIFO (Last In, First Out), que significa “último a entrar, primeiro a sair”. 
//Ela é indicada para situações em que precisamos retirar primeiro o elemento que foi colocado por último.

//Fila: é uma estrutura de dados em que o primeiro elemento a entrar é o primeiro a sair. 
//Essa regra é chamada de FIFO (First In, First Out), que significa “primeiro a entrar, primeiro a sair”. 
//Ela é indicada para situações em que os elementos precisam ser atendidos ou retirados na ordem em que chegaram.

//B) Por que a pilha controla uma ponta e a fila controla duas?
//Pilha: controla apenas uma ponta, chamada de topo, porque os elementos são adicionados e retirados pelo mesmo lugar. 
//O último elemento colocado fica em cima e é o primeiro que pode ser retirado.

//Fila: precisa controlar duas pontas, chamadas de frente e fundo. 
//A frente é o lugar de onde os elementos são retirados, enquanto o fundo é o lugar onde novos elementos são adicionados. 
//Isso permite que a fila siga a regra FIFO, mantendo a ordem de chegada.

//C) Exemplos do dia a dia
//Exemplo de pilha: empilhar cartas de um baralho dentro de uma caixa. 
//Cada carta é colocada sobre a anterior e, para retirar uma carta sem bagunçar a pilha, é necessário começar pela carta que está no topo. 
//Isso representa a regra LIFO.

//Exemplo de fila: uma máquina de bebidas que armazena latas em uma sequência. 
//A primeira lata da frente é a primeira a ser retirada quando alguém compra uma bebida, enquanto as novas latas são colocadas pelo fundo. 
//Assim, a primeira lata que entra é a primeira que sai, seguindo a regra FIFO.
